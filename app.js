function initializeObserver() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.2 });

  document.querySelectorAll("[data-observe]").forEach((section) => observer.observe(section));
}

function openModal(id) {
  const modal = document.getElementById(id);
  if (!modal) return;
  const backdrop = document.getElementById("modal-backdrop");
  backdrop.hidden = false;
  requestAnimationFrame(() => backdrop.classList.add("active"));
  modal.hidden = false;
  document.body.classList.add("no-scroll");
  state.activeModal = id;
  state.focusRestore = document.activeElement;
  const focusable = getFocusable(modal);
  if (focusable.length) focusable[0].focus();
  state.trapCleanup = trapFocus(modal, () => closeModal(id));
  modal.addEventListener("keydown", modalKeydown);
}

function closeModal(id) {
  const modal = document.getElementById(id);
  if (!modal || modal.hidden) return;
  modal.hidden = true;
  modal.removeEventListener("keydown", modalKeydown);
  const backdrop = document.getElementById("modal-backdrop");
  backdrop.classList.remove("active");
  setTimeout(() => {
    backdrop.hidden = true;
  }, 200);
  document.body.classList.remove("no-scroll");
  if (state.trapCleanup) state.trapCleanup();
  state.trapCleanup = null;
  if (state.focusRestore) {
    state.focusRestore.focus();
    state.focusRestore = null;
  }
  state.activeModal = null;
}

function modalKeydown(event) {
  if (event.key === "Escape") {
    const modal = event.currentTarget;
    closeModal(modal.id);
  }
}

function trapFocus(container, onClose) {
  const handleKeydown = (event) => {
    if (event.key !== "Tab") return;
    const focusable = getFocusable(container);
    if (!focusable.length) return;
    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  };

  const handleFocusTrap = (event) => {
    if (event.key === "Escape" && onClose) {
      onClose();
    }
  };

  container.addEventListener("keydown", handleKeydown);
  container.addEventListener("keydown", handleFocusTrap);

  return () => {
    container.removeEventListener("keydown", handleKeydown);
    container.removeEventListener("keydown", handleFocusTrap);
  };
}

function getFocusable(node) {
  return Array.from(node.querySelectorAll(selectors.focusable)).filter((el) => !el.hasAttribute("disabled") && el.tabIndex !== -1);
}

function getSakeById(id) {
  for (const pref of prefectureData.prefectures) {
    const found = pref.sakes.find((sake) => sake.id === id);
    if (found) return found;
  }
  return null;
}
